def run(dry_run: bool = True, destaff: bool = True):
    log: list[str] = []
    mode = "DRY RUN — nothing written" if dry_run else "APPLYING CHANGES"
    log.append(f"=== {mode} ===\n")

    # 1. permissions -------------------------------------------------------
    log.append("--- Instructor role permissions ---")
    before = _current_instructor_perms()
    for doctype, spec in INSTRUCTOR_PERMS.items():
        line = _set_perm(doctype, spec, dry_run)
        if line:
            log.append(line)

    stale = sorted(set(before) - set(INSTRUCTOR_PERMS))
    for doctype in stale:
        log.append(f"  REVOKE Instructor entirely on {doctype}")
        if not dry_run:
            for table in ("Custom DocPerm", "DocPerm"):
                for nm in frappe.db.get_all(table, filters={"parent": doctype, "role": "Instructor"}, pluck="name"):
                    frappe.delete_doc(table, nm, ignore_permissions=True, force=True)

    # 2. permission queries ------------------------------------------------
    log.append("\n--- Permission query scripts ---")
    for doctype, script in PERMISSION_QUERIES.items():
        log.append(_upsert_script(f"{doctype} Scope", "Permission Query", doctype, script, dry_run))

    # 3. homeroom write guards --------------------------------------------
    log.append("\n--- Homeroom write guards ---")
    for doctype in HOMEROOM_GUARDED_DOCTYPES:
        log.append(_upsert_script(
            f"{doctype} Homeroom Guard", "DocType Event", doctype,
            HOMEROOM_GUARD, dry_run, event="Before Save",
        ))

    # 4. reviewer anonymity ------------------------------------------------
    log.append("\n--- Teacher Evaluation reviewer anonymity ---")
    line = _reviewer_permlevel(dry_run)
    log.append(line or "  (already set)")

    # 5. role assignments --------------------------------------------------
    if destaff:
        log.append("\n--- Removing `Academics User` from linked teachers ---")
        targets = _teachers_to_destaff() + [
            u for u in EXTRA_DESTAFF if frappe.db.exists("Has Role", {"parent": u, "role": "Academics User"})
        ]
        log.append(f"  {len(targets)} accounts affected")
        for user in targets:
            log.append(f"    - {user}")
            if not dry_run:
                for nm in frappe.db.get_all("Has Role", filters={"parent": user, "role": "Academics User"}, pluck="name"):
                    frappe.delete_doc("Has Role", nm, ignore_permissions=True, force=True)

    if not dry_run:
        frappe.clear_cache()
        frappe.db.commit()
        log.append("\n=== committed, caches cleared ===")
    else:
        log.append("\n=== dry run complete, nothing written ===")

    out = "\n".join(log)
    print(out)
    return out
