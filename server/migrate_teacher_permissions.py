"""
Refine the `Instructor` role and de-scope teachers from `Academics User`.

Run with:
    bench --site app.makkobillischool.com execute \
        mbs.migrate_teacher_permissions.run --kwargs "{'dry_run': True}"

or paste into `bench --site app.makkobillischool.com console` and call run().

ALWAYS run with dry_run=True first and read the diff it prints.

Design decisions this implements (agreed 2026-09-17):
  * No new role. The existing `Instructor` role is reshaped in place.
  * `Academics User` is removed from real teachers; the 17 leadership
    accounts and the unlinked-but-active staff keep it.
  * Reads are scoped with Permission Query server scripts following the
    site's existing house pattern (set `conditions` only when the role
    matches, leave empty otherwise, so multiple scripts AND cleanly).
  * Late/sick/permission records: any teacher may READ them for students
    in their own sections; only the HOMEROOM teacher of the student's
    section may CREATE or MODIFY them. Enforced by validate hooks, since
    permission queries scope reads only.
  * Appeals stay with Education Manager / System Manager.
  * `Teacher Evaluation.reviewer` moves to permlevel 1 so teachers can
    read their own ratings without ever seeing who submitted them.
"""

