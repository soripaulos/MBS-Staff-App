def _current_instructor_perms() -> dict[str, dict]:
    out: dict[str, dict] = {}
    for table in ("Custom DocPerm", "DocPerm"):
        rows = frappe.db.get_all(
            table,
            filters={"role": "Instructor", "permlevel": 0},
            fields=["parent"] + list(PERM_FIELDS),
        )
        for r in rows:
            out.setdefault(r["parent"], {k: r.get(k) or 0 for k in PERM_FIELDS})
    return out


def _set_perm(doctype: str, spec: dict, dry_run: bool) -> str | None:
    """Write one Custom DocPerm row for the Instructor role."""
    target = {f: int(spec.get(f, 0)) for f in PERM_FIELDS}
    target["read"] = int(spec.get("read", 1))

    existing = frappe.db.get_value(
        "Custom DocPerm",
        {"parent": doctype, "role": "Instructor", "permlevel": 0},
        "name",
    )
    if existing:
        before = frappe.db.get_value("Custom DocPerm", existing, list(PERM_FIELDS), as_dict=True)
        changed = {f: (before.get(f), target[f]) for f in PERM_FIELDS if int(before.get(f) or 0) != target[f]}
        if not changed:
            return None
        if not dry_run:
            frappe.db.set_value("Custom DocPerm", existing, target)
        return f"  UPDATE {doctype}: " + ", ".join(f"{f} {a}->{b}" for f, (a, b) in changed.items())

    if not dry_run:
        doc = frappe.get_doc({
            "doctype": "Custom DocPerm",
            "parent": doctype,
            "parenttype": "DocType",
            "parentfield": "permissions",
            "role": "Instructor",
            "permlevel": 0,
            **target,
        })
        doc.insert(ignore_permissions=True)
    return f"  CREATE {doctype}: " + ", ".join(f"{f}={v}" for f, v in target.items() if v)


def _upsert_script(name: str, script_type: str, doctype: str, script: str,
                   dry_run: bool, event: str | None = None) -> str:
    full_name = f"{SCRIPT_PREFIX} {name}"
    existing = frappe.db.exists("Server Script", full_name)
    payload = {
        "script_type": script_type,
        "reference_doctype": doctype,
        "script": script,
        "disabled": 0,
    }
    if event:
        payload["doctype_event"] = event

    if existing:
        if dry_run:
            return f"  UPDATE script {full_name}"
        doc = frappe.get_doc("Server Script", full_name)
        doc.update(payload)
        doc.save(ignore_permissions=True)
        return f"  UPDATE script {full_name}"

    if dry_run:
        return f"  CREATE script {full_name} ({script_type} on {doctype})"
    doc = frappe.get_doc({"doctype": "Server Script", "name": full_name, **payload})
    doc.insert(ignore_permissions=True)
    return f"  CREATE script {full_name} ({script_type} on {doctype})"


def _reviewer_permlevel(dry_run: bool) -> str:
    """Move Teacher Evaluation.reviewer to permlevel 1 and grant it to admins."""
    lines = []
    ps = frappe.db.exists("Property Setter", {
        "doc_type": "Teacher Evaluation", "field_name": "reviewer", "property": "permlevel",
    })
    if not ps:
        lines.append("  SET Teacher Evaluation.reviewer -> permlevel 1")
        if not dry_run:
            frappe.get_doc({
                "doctype": "Property Setter",
                "doctype_or_field": "DocField",
                "doc_type": "Teacher Evaluation",
                "field_name": "reviewer",
                "property": "permlevel",
                "property_type": "Int",
                "value": "1",
            }).insert(ignore_permissions=True)

    for role in ("System Manager", "Education Manager"):
        if not frappe.db.exists("Custom DocPerm", {
            "parent": "Teacher Evaluation", "role": role, "permlevel": 1,
        }):
            lines.append(f"  GRANT permlevel 1 read on Teacher Evaluation to {role}")
            if not dry_run:
                frappe.get_doc({
                    "doctype": "Custom DocPerm",
                    "parent": "Teacher Evaluation",
                    "parenttype": "DocType",
                    "parentfield": "permissions",
                    "role": role,
                    "permlevel": 1,
                    "read": 1,
                    "write": 1,
                }).insert(ignore_permissions=True)
    return "\n".join(lines)


