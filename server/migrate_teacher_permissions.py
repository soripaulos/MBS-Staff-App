# --------------------------------------------------------------------------
# 2. Permission query scripts
# --------------------------------------------------------------------------
# Shared preamble. A user is treated as a "scoped teacher" only when they
# hold Instructor and none of the elevated roles — so leadership, the
# registrar and System Manager are never narrowed by these scripts, and
# the existing Scholarship Supervisor scripts still AND in cleanly.

PREAMBLE = """
user_roles = set(frappe.db.get_all("Has Role", filters={"parent": frappe.session.user}, pluck="role"))
ELEVATED = {"System Manager", "Education Manager", "Director", "Academics User", "DD Student Registrar"}
if "Instructor" in user_roles and not (user_roles & ELEVATED):
    instructor = frappe.db.get_value("Instructor", {"custom_username": frappe.session.user}, "name")
    if not instructor:
        conditions = "1=0"
    else:
        ins = frappe.db.escape(instructor)
"""

# Groups the teacher teaches or is homeroom of.
MY_GROUPS = """(
            SELECT sg.name FROM `tabStudent Group` sg
            WHERE sg.disabled = 0 AND (
                sg.custom_homeroom_teacher = {ins}
                OR sg.name IN (
                    SELECT sgi.parent FROM `tabStudent Group Instructor` sgi
                    WHERE sgi.instructor = {ins}
                )
            )
        )"""

# Students inside those groups.
MY_STUDENTS = """(
            SELECT sgs.student FROM `tabStudent Group Student` sgs
            WHERE sgs.active = 1 AND sgs.parent IN {my_groups}
        )""".replace("{my_groups}", MY_GROUPS)


def _student_scoped(table: str, field: str = "student") -> str:
    """Restrict a doctype to students in the teacher's own sections."""
    return (
        PREAMBLE
        + f'        conditions = "`tab{table}`.{field} IN " + """{MY_STUDENTS}""".format(ins=ins)\n'
    )


